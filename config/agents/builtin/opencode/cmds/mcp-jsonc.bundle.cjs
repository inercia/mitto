function commaBetween(text, start, end) {
  let inString = false;
  let escaped = false;
  for (let i = start;i < end; i++) {
    const ch = text[i];
    if (inString) {
      if (escaped)
        escaped = false;
      else if (ch === "\\")
        escaped = true;
      else if (ch === '"')
        inString = false;
    } else if (ch === '"')
      inString = true;
    else if (text.startsWith("//", i)) {
      const newline = text.indexOf(`
`, i + 2);
      i = newline < 0 || newline >= end ? end : newline;
    } else if (text.startsWith("/*", i)) {
      const close = text.indexOf("*/", i + 2);
      i = close < 0 || close >= end ? end : close + 1;
    } else if (ch === ",")
      return i;
  }
  return -1;
}
function removeServer(text, name) {
  const errors = [];
  const root = parseTree2(text, errors, { allowTrailingComma: true, disallowComments: false });
  if (errors.length || !root)
    throw new Error(`invalid JSONC (parse error ${errors[0]?.error ?? "unknown"})`);
  const property = (object, key) => object?.children?.find((child) => child.type === "property" && child.children?.[0]?.value === key);
  const mcpNode = property(root, "mcp")?.children?.[1];
  const objectProperties = mcpNode?.children || [];
  const index = objectProperties.findIndex((child) => child.children?.[0]?.value === name);
  if (index < 0)
    throw new Error(`MCP server ${JSON.stringify(name)} not found`);
  const node = objectProperties[index];
  const previous = objectProperties[index - 1];
  const next = objectProperties[index + 1];
  const edits = [{ offset: node.offset, length: node.length, content: "" }];
  if (next) {
    const comma = commaBetween(text, node.offset + node.length, next.offset);
    if (comma >= 0)
      edits.push({ offset: comma, length: 1, content: "" });
  } else {
    if (previous) {
      const comma = commaBetween(text, previous.offset + previous.length, node.offset);
      if (comma >= 0)
        edits.push({ offset: comma, length: 1, content: "" });
    }
    const closingBrace = mcpNode.offset + mcpNode.length - 1;
    const trailingComma = commaBetween(text, node.offset + node.length, closingBrace);
    if (trailingComma >= 0)
      edits.push({ offset: trailingComma, length: 1, content: "" });
  }
  return applyEdits(text, edits);
}
function writeAction(remove) {
  const input = JSON.parse(inputText);
  const name = input.name || "";
  if (!name)
    throw new Error("name is required");
  const configPath = targetConfig(input);
  let text;
  let config;
  try {
    text = import_node_fs.default.readFileSync(configPath, "utf8");
    config = parseConfig(text, configPath);
  } catch (error) {
    if (error.code !== "ENOENT")
      throw error;
    text = `{}
`;
    config = {};
    import_node_fs.default.mkdirSync(import_node_path.default.dirname(configPath), { recursive: true });
  }
  const servers = config.mcp || {};
  if (config.mcp != null && (typeof config.mcp !== "object" || Array.isArray(config.mcp))) {
    throw new Error(`${configPath}: OpenCode config mcp property must be an object`);
  }
  if (remove && !Object.hasOwn(servers, name))
    throw new Error(`MCP server ${JSON.stringify(name)} not found`);
  if (!remove && !input.command && !input.url)
    throw new Error("either command or url is required");
  let output;
  if (remove)
    output = removeServer(text, name);
  else {
    const entry = input.url ? { type: "remote", url: input.url, ...input.headers ? { headers: input.headers } : {} } : { type: "local", command: [input.command, ...input.args || []], ...input.env ? { environment: input.env } : {} };
    const edits = modify(text, ["mcp", name], entry, { formattingOptions: { insertSpaces: true, tabSize: 2 } });
    output = applyEdits(text, edits);
  }
  import_node_fs.default.writeFileSync(configPath, output, "utf8");
  return { success: true, message: `${remove ? "Removed" : "Added"} MCP server ${JSON.stringify(name)}`, name };
}
try {
  const result = action === "list" ? list() : action === "install" ? writeAction(false) : action === "remove" ? writeAction(true) : (() => {
    throw new Error(`unknown action: ${action}`);
  })();
  process.stdout.write(`${JSON.stringify(result)}
`);
} catch (error) {
  if (action === "list") {
    process.stderr.write(`${error.message}
`);
    process.exitCode = 1;
  } else {
    const name = (() => {
      try {
        return JSON.parse(inputText).name || "";
      } catch {
        return "";
      }
    })();
    process.stdout.write(`${JSON.stringify({ success: false, message: error.message, name })}
`);
    process.exitCode = 1;
  }
}
